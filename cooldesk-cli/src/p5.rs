//! P5: things generated from the app's live command manifest (`GET /cli/commands`).
//!
//! * `docs`: a Markdown command reference. Generated, so it can't drift from the app.
//!   The hand-written OPERATOR-GUIDE.md explains *how* to operate; this lists *what* exists.
//! * `completions`: shell completions. `invoke <cmd>` completes the manifest's command
//!   names when the app is reachable at generation time.
//! * `batch`: NDJSON in, NDJSON out, one `/cli/invoke` per line.

use crate::{Client, Failure, R};
use serde_json::{json, Value};
use std::io::{BufRead, Write};

/// Stable section order and blurbs for each tier.
const TIERS: &[(&str, &str)] = &[
    ("read", "No side effects. Safe to run any time."),
    ("act", "Opens, launches, focuses, adds or toggles something. Nothing is lost."),
    ("destructive", "Closes, kills, deletes, runs arbitrary input, or changes a security setting. Needs `--yes` (CLI) or `confirm: true` (MCP)."),
    ("secret", "Touches the password vault. Needs `--yes`. Not exposed over MCP by default."),
];

fn arg_line(a: &Value) -> String {
    format!(
        "`{}` {}{}",
        a["name"].as_str().unwrap_or("?"),
        a["type"].as_str().unwrap_or("?"),
        if a["required"].as_bool() == Some(true) { "" } else { " (optional)" }
    )
}

fn example(cmd: &Value) -> String {
    let name = cmd["name"].as_str().unwrap_or("");
    let mut obj = serde_json::Map::new();
    for a in cmd["args"].as_array().into_iter().flatten().filter(|a| a["required"].as_bool() == Some(true)) {
        let v = match a["type"].as_str().unwrap_or("") {
            "string" => json!("…"),
            "string[]" => json!(["…"]),
            "bool" => json!(true),
            "f64" => json!(1.0),
            "json" | "object" => json!({}),
            _ => json!(0),
        };
        obj.insert(a["name"].as_str().unwrap_or("").to_string(), v);
    }
    let json_part = if obj.is_empty() { String::new() } else { format!(" --json '{}'", Value::Object(obj)) };
    let yes = if matches!(cmd["tier"].as_str(), Some("destructive" | "secret")) { " --yes" } else { "" };
    format!("cooldesk-cli invoke {name}{json_part}{yes}")
}

/// Render the Markdown reference from a manifest and an app version. Pure, so it can be tested.
pub fn render_docs(manifest: &Value, app_version: &str) -> String {
    let cmds: Vec<&Value> = manifest["commands"].as_array().map(|a| a.iter().collect()).unwrap_or_default();
    let mut out = String::new();
    out.push_str("# CoolDesk command reference (generated)\n\n");
    out.push_str(&format!(
        "Generated by `cooldesk-cli docs` from the live manifest (`GET /cli/commands`) of CoolDesk {app_version}. \
         Do not edit by hand; regenerate it. How to operate the app: [OPERATOR-GUIDE.md](OPERATOR-GUIDE.md).\n\n"
    ));
    out.push_str("| tier | commands | meaning |\n|---|---|---|\n");
    for (tier, blurb) in TIERS {
        let n = cmds.iter().filter(|c| c["tier"].as_str() == Some(tier)).count();
        out.push_str(&format!("| `{tier}` | {n} | {blurb} |\n"));
    }
    out.push_str(&format!("| **total** | **{}** | |\n\n", cmds.len()));
    for (tier, _) in TIERS {
        let mut group: Vec<&&Value> = cmds.iter().filter(|c| c["tier"].as_str() == Some(tier)).collect();
        if group.is_empty() {
            continue;
        }
        group.sort_by_key(|c| c["name"].as_str().unwrap_or("").to_string());
        out.push_str(&format!("## {tier}\n\n"));
        for c in group {
            let args: Vec<String> = c["args"].as_array().into_iter().flatten().map(arg_line).collect();
            out.push_str(&format!("### `{}`\n\n{}\n\n", c["name"].as_str().unwrap_or(""), c["summary"].as_str().unwrap_or("")));
            out.push_str(&format!("- **Args:** {}\n", if args.is_empty() { "none".into() } else { args.join(", ") }));
            out.push_str(&format!("- **Example:** `{}`\n\n", example(c)));
        }
    }
    if let Some(ex) = manifest["excluded"].as_array().filter(|e| !e.is_empty()) {
        out.push_str("## Not exposed (UI-only), with the reason\n\n| IPC command | why |\n|---|---|\n");
        let mut ex: Vec<&Value> = ex.iter().collect();
        ex.sort_by_key(|e| e["name"].as_str().unwrap_or("").to_string());
        for e in ex {
            out.push_str(&format!("| `{}` | {} |\n", e["name"].as_str().unwrap_or(""), e["reason"].as_str().unwrap_or("")));
        }
    }
    out
}

pub fn docs(c: &Client, out: Option<&str>) -> R<Value> {
    let manifest = c.get("/cli/commands", &[])?;
    let version = c
        .post("/cli/invoke", &json!({ "cmd": "get_app_version" }))
        .ok()
        .and_then(|v| v["result"].as_str().map(String::from))
        .unwrap_or_else(|| "unknown".into());
    let md = render_docs(&manifest, &version);
    match out {
        Some(path) => {
            std::fs::write(path, &md).map_err(|e| Failure::Usage(format!("cannot write {path}: {e}")))?;
            Ok(json!({ "ok": true, "wrote": path, "commands": manifest["commands"].as_array().map(|a| a.len()), "bytes": md.len() }))
        }
        None => {
            print!("{md}");
            Ok(Value::Null)
        }
    }
}

/// The clap command tree for completions. When the manifest is reachable,
/// `invoke <CMD>` and `commands --tier` get their possible values from it.
pub fn completion_command(names: Option<Vec<String>>) -> clap::Command {
    use clap::CommandFactory;
    let mut cmd = crate::Cli::command();
    cmd = cmd.mut_subcommand("commands", |s| {
        s.mut_arg("tier", |a| a.value_parser(["read", "act", "destructive", "secret"]))
    });
    if let Some(names) = names {
        // clap wants 'static strings here. This command is built once, just before the
        // process prints completions and exits, so leaking ~125 short names is fine.
        let values: Vec<clap::builder::PossibleValue> = names
            .into_iter()
            .map(|n| clap::builder::PossibleValue::new(&*Box::leak(n.into_boxed_str())))
            .collect();
        cmd = cmd.mut_subcommand("invoke", |s| s.mut_arg("cmd", |a| a.value_parser(clap::builder::PossibleValuesParser::new(values))));
    }
    cmd
}

/// (name, "summary [tier]") for every manifest command, sorted by name.
pub fn manifest_entries(c: &Client) -> Option<Vec<(String, String)>> {
    let m = c.get("/cli/commands", &[]).ok()?;
    let mut v: Vec<(String, String)> = m["commands"]
        .as_array()?
        .iter()
        .filter_map(|c| {
            Some((
                c["name"].as_str()?.to_string(),
                format!("{} [{}]", c["summary"].as_str().unwrap_or(""), c["tier"].as_str().unwrap_or("")),
            ))
        })
        .collect();
    v.sort();
    Some(v)
}

/// Generate completions. bash and zsh get the manifest's command names from the
/// value parser. clap_complete's PowerShell and fish generators don't emit
/// possible values for positional args, so the names are spliced in after
/// generation. elvish doesn't emit them either and isn't spliced, so it
/// completes subcommands and flags only (elvish is rarely used on Windows).
pub fn completions(shell: clap_complete::Shell, entries: Option<Vec<(String, String)>>) -> String {
    use clap_complete::Shell;
    let mut cmd = completion_command(entries.as_ref().map(|e| e.iter().map(|(n, _)| n.clone()).collect()));
    let mut buf = Vec::new();
    clap_complete::generate(shell, &mut cmd, "cooldesk-cli", &mut buf);
    let mut out = String::from_utf8(buf).unwrap_or_default();
    let Some(entries) = entries else { return out };
    match shell {
        Shell::PowerShell => {
            let anchor = "'cooldesk-cli;invoke' {\n";
            if let Some(pos) = out.find(anchor) {
                let ins: String = entries
                    .iter()
                    .map(|(n, d)| {
                        format!(
                            "            [CompletionResult]::new('{n}', '{n}', [CompletionResultType]::ParameterValue, '{}')\n",
                            d.replace('\'', "''")
                        )
                    })
                    .collect();
                out.insert_str(pos + anchor.len(), &ins);
            }
        }
        Shell::Fish => {
            for (n, d) in &entries {
                out.push_str(&format!(
                    "complete -c cooldesk-cli -n \"__fish_cooldesk_cli_using_subcommand invoke\" -f -a \"{n}\" -d '{}'\n",
                    d.replace('\'', "\\'")
                ));
            }
        }
        _ => {}
    }
    out
}

/// Parse one batch line into an `/cli/invoke` body. `confirm` is honored only
/// when the whole batch was started with `--yes`. Pure.
pub fn batch_request(line: &str, allow_confirm: bool) -> Result<Value, String> {
    let v: Value = serde_json::from_str(line).map_err(|e| format!("not JSON: {e}"))?;
    let cmd = v["cmd"].as_str().ok_or("missing \"cmd\"")?;
    let args = v.get("args").cloned().unwrap_or_else(|| json!({}));
    if !args.is_object() {
        return Err("\"args\" must be an object".into());
    }
    let confirm = allow_confirm && v["confirm"].as_bool() == Some(true);
    Ok(json!({ "cmd": cmd, "args": args, "confirm": confirm }))
}

/// Returns the number of failed lines.
pub fn batch(c: &Client, allow_confirm: bool, stop_on_error: bool) -> usize {
    let stdin = std::io::stdin();
    let mut out = std::io::stdout();
    let mut failed = 0;
    for (i, line) in stdin.lock().lines().enumerate() {
        let Ok(line) = line else { break };
        if line.trim().is_empty() || line.trim_start().starts_with('#') {
            continue;
        }
        let n = i + 1;
        let row = match batch_request(&line, allow_confirm) {
            Err(e) => json!({ "line": n, "ok": false, "error": e }),
            Ok(body) => match c.post("/cli/invoke", &body) {
                Ok(v) => json!({ "line": n, "ok": true, "cmd": body["cmd"], "result": v.get("result").cloned().unwrap_or(Value::Null) }),
                Err(e) => json!({ "line": n, "ok": false, "cmd": body["cmd"], "error": crate::failure_message(&e) }),
            },
        };
        let ok = row["ok"].as_bool() == Some(true);
        let _ = writeln!(out, "{row}");
        let _ = out.flush();
        if !ok {
            failed += 1;
            if stop_on_error {
                break;
            }
        }
    }
    failed
}

#[cfg(test)]
mod tests {
    use super::*;

    fn manifest() -> Value {
        json!({
            "commands": [
                { "name": "kill_process", "tier": "destructive", "summary": "Kill", "args": [{ "name": "pid", "type": "u32", "required": true }] },
                { "name": "get_app_version", "tier": "read", "summary": "Version", "args": [] },
                { "name": "launch_app", "tier": "act", "summary": "Launch", "args": [{ "name": "path", "type": "string", "required": true }, { "name": "x", "type": "bool", "required": false }] }
            ],
            "excluded": [{ "name": "terminal_open", "reason": "channel" }]
        })
    }

    #[test]
    fn docs_have_counts_sections_examples_and_exclusions() {
        let md = render_docs(&manifest(), "9.9.9");
        assert!(md.contains("CoolDesk 9.9.9"));
        assert!(md.contains("| `read` | 1 |") && md.contains("| `destructive` | 1 |") && md.contains("| **total** | **3** |"));
        assert!(md.find("## read").unwrap() < md.find("## act").unwrap(), "tier order is stable");
        assert!(md.contains("`cooldesk-cli invoke kill_process --json '{\"pid\":0}' --yes`"));
        assert!(md.contains("`path` string, `x` bool (optional)"));
        assert!(md.contains("`cooldesk-cli invoke get_app_version`"));
        assert!(md.contains("| `terminal_open` | channel |"));
        assert!(!md.contains("## secret"), "empty tiers are omitted");
    }

    #[test]
    fn batch_confirm_only_with_global_yes() {
        let line = r#"{"cmd":"close_app","args":{"pid":1},"confirm":true}"#;
        assert_eq!(batch_request(line, false).unwrap()["confirm"], json!(false));
        assert_eq!(batch_request(line, true).unwrap()["confirm"], json!(true));
        assert_eq!(batch_request(r#"{"cmd":"x"}"#, true).unwrap()["args"], json!({}));
        assert!(batch_request("nope", true).is_err());
        assert!(batch_request(r#"{"args":{}}"#, true).is_err());
        assert!(batch_request(r#"{"cmd":"x","args":[1]}"#, true).is_err());
    }

    #[test]
    fn completions_include_manifest_names_in_every_shell() {
        use clap_complete::Shell;
        let entries = || Some(vec![("kill_process".to_string(), "Kill it's tree [destructive]".to_string()), ("launch_app".to_string(), "Launch [act]".to_string())]);
        for shell in [Shell::Bash, Shell::Zsh, Shell::Fish, Shell::PowerShell] {
            let s = completions(shell, entries());
            assert!(s.contains("launch_app") && s.contains("kill_process"), "{shell:?} lacks manifest names");
        }
        let ps = completions(Shell::PowerShell, entries());
        let block = &ps[ps.find("'cooldesk-cli;invoke' {").unwrap()..];
        assert!(block.contains("[CompletionResult]::new('kill_process', 'kill_process', [CompletionResultType]::ParameterValue, 'Kill it''s tree [destructive]')"), "PS quote escaping");
        assert!(completions(Shell::Bash, entries()).contains("destructive"), "tier values complete too");
        assert!(!completions(Shell::Bash, None).contains("kill_process"), "no app, no names");
    }
}
